#include "graphics/gfx_icons.h"

#define ENVELOPE_WIDTH   30
#define ENVELOPE_HEIGHT  20

/*
 * Envelope icon bitmap.
 *
 * Pixel format:
 * 0 = white
 * 1 = black
 *
 * One bit per pixel, packed MSB-first.
 * Each row is padded to a whole number of bytes; unused bits are ignored.
 */
static const uint8_t envelope_data
    [ENVELOPE_HEIGHT][(ENVELOPE_WIDTH + 7) / 8] = {
    {0xFF, 0xFF, 0xFF, 0xFC},
    {0xFF, 0xFF, 0xFF, 0xFC},
    {0xF0, 0x00, 0x00, 0x3C},
    {0xD8, 0x00, 0x00, 0x6C},
    {0xCC, 0x00, 0x00, 0xCC},
    {0xC6, 0x00, 0x01, 0x8C},
    {0xC1, 0x80, 0x06, 0x0C},
    {0xC3, 0x00, 0x0C, 0x0C},
    {0xC0, 0xC0, 0x0C, 0x0C},
    {0xC0, 0x60, 0x18, 0x0C},
    {0xC0, 0x3F, 0xF0, 0x0C},
    {0xC0, 0x00, 0x00, 0x0C},
    {0xC0, 0x00, 0x00, 0x0C},
    {0xC0, 0x00, 0x00, 0x0C},
    {0xC0, 0x00, 0x00, 0x0C},
    {0xC0, 0x00, 0x00, 0x0C},
    {0xC0, 0x00, 0x00, 0x0C},
    {0xC0, 0x00, 0x00, 0x0C},
    {0xFF, 0xFF, 0xFF, 0xFC},
    {0xFF, 0xFF, 0xFF, 0xFC}
};

/* Public icon descriptor */
const gfx_icons_t gfx_icon_envelope = {
    .width  = ENVELOPE_WIDTH,
    .height = ENVELOPE_HEIGHT,
    .data   = &envelope_data[0][0]
};
